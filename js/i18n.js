// Initialize i18n
function initI18n() {
    const savedLang = localStorage.getItem('language') || 'kn';
    setLanguage(savedLang);
    updateLanguageSwitcher();
}

// Set language
function setLanguage(lang) {
    if (!translations[lang]) lang = 'kn';
    localStorage.setItem('language', lang);
    document.documentElement.lang = lang;

    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        element.textContent = t(key);
    });

    // Update placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
        const key = element.getAttribute('data-i18n-placeholder');
        element.placeholder = t(key);
    });

    updateLanguageSwitcher();
}

// Translate function
function t(key) {
    const lang = localStorage.getItem('language') || 'kn';
    return translations[lang][key] || translations['kn'][key] || key;
}

// Update language switcher UI
function updateLanguageSwitcher() {
    const currentLang = localStorage.getItem('language') || 'kn';
    document.querySelectorAll('.lang-btn').forEach(btn => {
        if (btn.getAttribute('data-lang') === currentLang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });
}

// Initialize on page load
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initI18n);
} else {
    initI18n();
}
